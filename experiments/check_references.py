#!/usr/bin/env python3
"""Audit paper/references.bib and emit a verification checklist.

Citations are the one part of a paper that a reader can check trivially and that
a model cannot verify from memory. This script does not invent anything: it
reports what each entry carries and what is missing, so the missing parts can be
looked up once, by hand, in a database.

    python3 experiments/check_references.py            # report
    python3 experiments/check_references.py --write    # also write the checklist
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from typing import Dict, List, Tuple

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BIB = os.path.join(ROOT, "paper", "references.bib")
OUT = os.path.join(ROOT, "docs", "reference-checklist.md")


def parse_bib(path: str) -> List[Tuple[str, str, Dict[str, str]]]:
    text = open(path, encoding="utf-8").read()
    entries: List[Tuple[str, str, Dict[str, str]]] = []
    for match in re.finditer(r"@(\w+)\{([^,]+),", text):
        kind, key = match.group(1), match.group(2).strip()
        start = match.end()
        depth, i = 1, match.start() + len(match.group(0)) - 1
        while i < len(text) and depth:
            if text[i] == "{":
                depth += 1
            elif text[i] == "}":
                depth -= 1
            i += 1
        body = text[start:i]
        fields = {m.group(1).lower(): m.group(2).strip()
                  for m in re.finditer(r"(\w+)\s*=\s*\{(.*?)\}\s*,?\s*(?=\w+\s*=|\Z)",
                                       body, re.S)}
        entries.append((key, kind, fields))
    return entries


def cited_keys() -> set:
    text = ""
    for name in ("body.tex", "abstract.tex", "body-pt.tex", "abstract-pt.tex"):
        path = os.path.join(ROOT, "paper", name)
        if os.path.exists(path):
            text += open(path, encoding="utf-8").read()
    keys = set()
    for group in re.findall(r"\\cite\{([^}]+)\}", text.replace("%\n", "")):
        keys.update(k.strip() for k in group.split(","))
    return keys


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()

    entries = parse_bib(BIB)
    cited = cited_keys()
    keys = {k for k, _, _ in entries}
    rows: List[str] = []
    missing_doi: List[str] = []
    for key, kind, fields in sorted(entries):
        has_doi = "doi" in fields
        has_url = "url" in fields or "howpublished" in fields
        title = re.sub(r"\s+", " ", fields.get("title", "?"))[:70]
        if kind in ("article", "inproceedings", "book", "techreport") and not has_doi:
            missing_doi.append(key)
        rows.append(f"| `{key}` | {kind} | {title} | {'yes' if has_doi else '**no**'} | "
                    f"{'yes' if has_url else 'no'} | {'yes' if key in cited else '**no**'} |")

    print(f"{len(entries)} entries, {len(cited)} cited")
    print(f"cited but absent from the bibliography: {sorted(cited - keys) or 'none'}")
    print(f"present but never cited: {sorted(keys - cited) or 'none'}")
    print(f"scholarly entries without a DOI: {len(missing_doi)}")

    if args.write:
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        with open(OUT, "w", encoding="utf-8") as fh:
            fh.write("# Reference verification checklist\n\n"
                     "Generated by `experiments/check_references.py`. Every row needs one\n"
                     "lookup before submission: confirm the author list, year, venue and DOI\n"
                     "against the publisher's own page. Entries written from memory are the\n"
                     "single easiest thing for a reviewer to catch.\n\n"
                     "| Key | Type | Title | DOI | URL | Cited |\n|---|---|---|---|---|---|\n")
            fh.write("\n".join(rows) + "\n\n")
            fh.write(f"**{len(missing_doi)} scholarly entries carry no DOI:** "
                     + ", ".join(f"`{k}`" for k in missing_doi) + ".\n")
        print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
