#!/usr/bin/env python3
"""Emit pgfplots versions of the result figures so that paper/main.tex compiles
with a stock pdflatex + pgfplots installation (no external image conversion).

    python3 experiments/make_tex_figures.py
"""

from __future__ import annotations

import csv
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
RES = os.path.join(ROOT, "experiments", "results")
TAB = os.path.join(RES, "tables")
OUT = os.path.join(ROOT, "paper", "figures")

HEAD = "% generated by experiments/make_tex_figures.py -- do not edit by hand\n"


def read(name):
    with open(os.path.join(TAB, name), newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def esc(text: str) -> str:
    return (str(text).replace("&", "\\&").replace("%", "\\%").replace("_", "\\_")
            .replace("#", "\\#"))


def xbar(path, labels, values, xlabel, caption, label, width="\\linewidth", height="7.2cm",
         fmt="{:.3f}", bar_color="MidnightBlue"):
    rows = "\n".join(f"        ({v:.6f},{i})" for i, v in enumerate(values))
    ticks = ",".join(str(i) for i in range(len(labels)))
    names = ",".join("{" + esc(l) + "}" for l in labels)
    body = f"""{HEAD}\\begin{{figure}}[t]
\\centering
\\begin{{tikzpicture}}
\\begin{{axis}}[
    xbar, width={width}, height={height},
    xlabel={{{esc(xlabel)}}},
    xmin=0, enlarge y limits=0.06,
    ytick={{{ticks}}}, yticklabels={{{names}}},
    y dir=reverse, ticklabel style={{font=\\scriptsize}},
    label style={{font=\\footnotesize}},
    nodes near coords, nodes near coords style={{font=\\tiny}},
    every node near coord/.append style={{/pgf/number format/fixed,
        /pgf/number format/precision=3}},
    xmajorgrids, grid style={{gray!25}}, axis lines*=left,
    bar width=6pt, tick align=outside,
]
\\addplot[fill={bar_color}!70, draw={bar_color}!80] coordinates {{
{rows}
}};
\\end{{axis}}
\\end{{tikzpicture}}
\\caption{{{caption}}}
\\label{{{label}}}
\\end{{figure}}
"""
    with open(os.path.join(OUT, path), "w", encoding="utf-8") as fh:
        fh.write(body)


def main() -> None:
    os.makedirs(OUT, exist_ok=True)
    summary = json.load(open(os.path.join(RES, "summary.json"), encoding="utf-8"))

    # --- Fig: most likely paths ------------------------------------------
    rows = read("e1_top_paths_production.csv")[:10]
    labels = []
    for r in rows:
        hops = r["path"].split(" -> ")[1:]
        labels.append(" $\\to$ ".join(h[:20].strip() for h in hops))
    xbar("fig_top_paths.tex", labels, [float(r["likelihood"]) for r in rows],
         "path likelihood $L(\\pi)$",
         "Ten most likely attack paths to production stoppage in the baseline "
         "configuration $S_0$. The highest-likelihood routes terminate in business "
         "and logistics systems, not in controllers.",
         "fig:top-paths", height="8cm")

    # --- Fig: technique mass ---------------------------------------------
    rows = read("e1_technique_mass.csv")[:12]
    xbar("fig_techniques.tex",
         [f"{r['technique']} {r['name'][:30]}" for r in rows],
         [float(r["likelihood_share"]) for r in rows],
         "share of aggregate path likelihood",
         "MITRE ATT\\&CK techniques ranked by the share of aggregate path likelihood "
         "that traverses them (Enterprise and ICS matrices combined).",
         "fig:techniques", height="7.6cm", bar_color="Maroon")

    # --- Fig: choke points -------------------------------------------------
    rows = read("e3_node_criticality.csv")[:12]
    xbar("fig_chokepoints.tex",
         [f"{r['name'][:30]} ({r['zone']})" for r in rows],
         [float(r["likelihood_share"]) for r in rows],
         "share of aggregate path likelihood traversing the asset",
         "Likelihood-weighted choke points of the reference architecture.",
         "fig:chokepoints", height="7.6cm", bar_color="OliveGreen")

    # --- Fig: control necessity -------------------------------------------
    nec = summary["E5"]["necessity"][:10]
    from capm.controls import CONTROLS
    xbar("fig_necessity.tex",
         [f"{n['control']} {CONTROLS[n['control']].name[:34]}" for n in nec],
         [max(n["delta_ale_if_removed"], 0.0) for n in nec],
         "ALE increase when the control is withdrawn (MUSD/plant-year)",
         "Necessity of each control inside the full programme $S_5$: the annualised "
         "loss that returns when that control alone is withdrawn.",
         "fig:necessity", height="6.4cm", bar_color="Purple")

    # --- Fig: scenario ALE by profile --------------------------------------
    scen = ["S0", "S1", "S2", "S3", "S4", "S5"]
    profiles = ["ransomware", "espionage", "sabotage"]
    colors = {"ransomware": "MidnightBlue", "espionage": "Maroon", "sabotage": "OliveGreen"}
    plots = []
    for p in profiles:
        coords = " ".join(f"({s},{summary['E4'][p][s]['ale_musd']})" for s in scen)
        plots.append(f"\\addplot[fill={colors[p]}!70, draw={colors[p]}!85] coordinates {{{coords}}};")
    body = f"""{HEAD}\\begin{{figure}}[t]
\\centering
\\begin{{tikzpicture}}
\\begin{{axis}}[
    ybar, width=\\linewidth, height=6.2cm,
    ylabel={{ALE (MUSD / plant-year)}},
    symbolic x coords={{{','.join(scen)}}}, xtick=data,
    ymin=0, bar width=5pt, enlarge x limits=0.10,
    legend style={{at={{(0.5,-0.22)}}, anchor=north, legend columns=3, font=\\scriptsize,
                   draw=none}},
    ticklabel style={{font=\\scriptsize}}, label style={{font=\\footnotesize}},
    ymajorgrids, grid style={{gray!25}}, axis lines*=left,
]
{chr(10).join(plots)}
\\legend{{{', '.join(profiles)}}}
\\end{{axis}}
\\end{{tikzpicture}}
\\caption{{Annualised loss expectancy per control scenario and actor profile.
Scenario $S_3$ lowers espionage risk sharply while \\emph{{increasing}} ransomware
risk: hardening the cheap data-theft routes displaces a rational actor onto the
availability objective.}}
\\label{{fig:scenario-ale}}
\\end{{figure}}
"""
    open(os.path.join(OUT, "fig_scenario_ale.tex"), "w", encoding="utf-8").write(body)

    # --- Fig: sensitivity ---------------------------------------------------
    sw = summary["E6"]["sweeps"]
    det = " ".join(f"({a},{b})" for a, b in sw["detection efficacy x"])
    freq = " ".join(f"({a},{b})" for a, b in sw["campaign frequency /yr"])
    body = f"""{HEAD}\\begin{{figure}}[t]
\\centering
\\begin{{tikzpicture}}
\\begin{{axis}}[
    width=\\linewidth, height=6.0cm,
    xlabel={{parameter multiplier (detection) or campaigns per year (frequency)}},
    ylabel={{ALE (MUSD / plant-year)}},
    ymin=0, legend style={{at={{(0.98,0.98)}}, anchor=north east, font=\\scriptsize, draw=none}},
    ticklabel style={{font=\\scriptsize}}, label style={{font=\\footnotesize}},
    xmajorgrids, ymajorgrids, grid style={{gray!25}}, axis lines*=left,
]
\\addplot[MidnightBlue, thick, mark=*] coordinates {{{det}}};
\\addplot[Maroon, thick, mark=square*] coordinates {{{freq}}};
\\legend{{detection efficacy multiplier, campaign frequency $\\lambda$}}
\\end{{axis}}
\\end{{tikzpicture}}
\\caption{{One-at-a-time sensitivity of the annualised loss expectancy. Halving
detection efficacy multiplies the baseline ALE by {summary['E6']['sweeps']['detection efficacy x'][0][1] / summary['E4_baseline_ale']:.1f};
the response to campaign frequency is linear by construction.}}
\\label{{fig:sensitivity}}
\\end{{figure}}
"""
    open(os.path.join(OUT, "fig_sensitivity.tex"), "w", encoding="utf-8").write(body)

    # --- Fig: efficient frontier -------------------------------------------
    greedy = read("e5_greedy_portfolio.csv")
    series = []
    for p in profiles:
        pts = [(0.0, summary["E4"][p]["S0"]["ale_musd"])]
        for r in greedy:
            if r["profile"] == p:
                pts.append((float(r["cumulative_cost"]), float(r["ale_after_musd"])))
        coords = " ".join(f"({x},{y})" for x, y in pts)
        series.append(f"\\addplot[{colors[p]}, thick, mark=*] coordinates {{{coords}}};")
    body = f"""{HEAD}\\begin{{figure}}[t]
\\centering
\\begin{{tikzpicture}}
\\begin{{axis}}[
    width=\\linewidth, height=6.0cm,
    xlabel={{cumulative control cost index}}, ylabel={{ALE (MUSD / plant-year)}},
    ymin=0, legend style={{at={{(0.98,0.98)}}, anchor=north east, font=\\scriptsize, draw=none}},
    ticklabel style={{font=\\scriptsize}}, label style={{font=\\footnotesize}},
    xmajorgrids, ymajorgrids, grid style={{gray!25}}, axis lines*=left,
]
{chr(10).join(series)}
\\legend{{{', '.join(profiles)}}}
\\end{{axis}}
\\end{{tikzpicture}}
\\caption{{Efficient frontier obtained by greedy selection on marginal risk
reduction per unit cost, for each actor profile.}}
\\label{{fig:frontier}}
\\end{{figure}}
"""
    open(os.path.join(OUT, "fig_frontier.tex"), "w", encoding="utf-8").write(body)

    # --- Fig: corpus planes -------------------------------------------------
    planes = ["it", "identity", "cloud", "ot", "supply_chain"]
    per = summary["E2"]["per_plane"]
    coords = " ".join(f"({p.replace('_',' ')},{per.get(p,0)})" for p in planes)
    body = f"""{HEAD}\\begin{{figure}}[t]
\\centering
\\begin{{tikzpicture}}
\\begin{{axis}}[
    ybar, width=\\linewidth, height=5.2cm,
    ylabel={{incidents}}, symbolic x coords={{{','.join(p.replace('_',' ') for p in planes)}}},
    xtick=data, ymin=0, bar width=14pt, enlarge x limits=0.14,
    nodes near coords, nodes near coords style={{font=\\scriptsize}},
    ticklabel style={{font=\\scriptsize}}, label style={{font=\\footnotesize}},
    ymajorgrids, grid style={{gray!25}}, axis lines*=left,
]
\\addplot[fill=MidnightBlue!65, draw=MidnightBlue] coordinates {{{coords}}};
\\end{{axis}}
\\end{{tikzpicture}}
\\caption{{Planes traversed by the 20 corpus incidents (2017--2025). Only two
incidents are reported to have interacted with equipment below Purdue level~3.}}
\\label{{fig:corpus-planes}}
\\end{{figure}}
"""
    open(os.path.join(OUT, "fig_corpus_planes.tex"), "w", encoding="utf-8").write(body)
    print("wrote pgfplots figures to", OUT)


if __name__ == "__main__":
    main()
