#!/usr/bin/env python3
"""Export the full model specification as machine- and human-readable tables.

    python3 experiments/export_model.py

Writes ``data/model_assets.csv``, ``data/model_edges.csv`` and
``docs/model-reference.md`` so that every parameter behind the paper can be
reviewed without reading Python.
"""

from __future__ import annotations

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from capm.architecture import AMPLIFIERS, build_graph
from capm.controls import CONTROLS
from capm.report import write_csv


def main() -> None:
    g = build_graph()
    write_csv(os.path.join(ROOT, "data", "model_assets.csv"),
              ["asset", "name", "zone", "zone_name", "purdue", "plane", "sl_target", "kind",
               "description"],
              [(a.id, a.name, a.zone, g.zones[a.zone].name, g.zones[a.zone].purdue,
                g.zones[a.zone].plane, g.zones[a.zone].sl_target, a.kind, a.description)
               for a in g.assets.values()])
    write_csv(os.path.join(ROOT, "data", "model_edges.csv"),
              ["src", "dst", "technique", "technique_name", "matrix", "tactic", "p", "delta",
               "effort_h", "crosses_zone", "src_zone", "dst_zone", "controls", "evidence",
               "rationale"],
              [(e.src, e.dst, e.technique, g.techniques[e.technique].name,
                g.techniques[e.technique].matrix, g.techniques[e.technique].tactic,
                e.p, e.delta, e.effort_h, int(g.crosses_zone(e)),
                g.assets[e.src].zone, g.assets[e.dst].zone,
                " ".join(e.controls), " ".join(e.evidence), e.rationale)
               for e in g.edges])

    lines = ["# Model reference", "",
             "Generated by `experiments/export_model.py`. Do not edit by hand.", "",
             "## Zones", "",
             "| Zone | Name | Purdue | Plane | SL-T |", "|---|---|---|---|---|"]
    for z in g.zones.values():
        lines.append(f"| {z.id} | {z.name} | {z.purdue} | {z.plane} | {z.sl_target} |")
    lines += ["", "## Consequence model", "",
              "| Impact | Downtime h (min, mode, max) | Loss rate MUSD/h | Fixed cost MUSD |",
              "|---|---|---|---|"]
    for impact, cons in g.consequences.items():
        lines.append(f"| {g.assets[impact].name} | {cons.downtime_h} | {cons.cost_per_h} | "
                     f"{cons.fixed_cost} |")
    lines += ["", "Recovery-inhibiting assets (outage multipliers): " +
              ", ".join(f"`{k}` x{v}" for k, v in AMPLIFIERS.items()), "",
              "## Controls", "",
              "| ID | Control | m | u | recovery | cost | IEC 62443-3-3 | NIST CSF 2.0 |",
              "|---|---|---|---|---|---|---|---|"]
    for cid in sorted(CONTROLS):
        c = CONTROLS[cid]
        lines.append(f"| {c.id} | {c.name} | {c.m:.2f} | {c.u:.2f} | {c.recovery:.2f} | "
                     f"{c.cost:.0f} | {'; '.join(c.iec62443)} | {'; '.join(c.csf)} |")
    lines += ["", "## Attack steps", "",
              "| Src | Dst | Technique | Matrix | p | delta | effort (h) | Controls | Evidence |",
              "|---|---|---|---|---|---|---|---|---|"]
    for e in g.edges:
        lines.append(f"| {e.src} | {e.dst} | {e.technique} {g.techniques[e.technique].name} | "
                     f"{g.techniques[e.technique].matrix} | {e.p:.2f} | {e.delta:.2f} | "
                     f"{e.effort_h:.0f} | {' '.join(e.controls)} | {' '.join(e.evidence)} |")
    os.makedirs(os.path.join(ROOT, "docs"), exist_ok=True)
    with open(os.path.join(ROOT, "docs", "model-reference.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote data/model_assets.csv, data/model_edges.csv, docs/model-reference.md")


if __name__ == "__main__":
    main()
