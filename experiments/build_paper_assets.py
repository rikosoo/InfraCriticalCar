def read(name: str) -> List[Dict[str, str]]:
    with open(os.path.join(TAB, name), newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def esc(text: object) -> str:
    return (str(text).replace("&", "\\&").replace("%", "\\%").replace("_", "\\_")
            .replace("#", "\\#"))


def cap(key: str, lang: str) -> str:
    return CAPTIONS[key][lang]


def lab(key: str, lang: str) -> str:
    return LABELS[key][lang]


class Renderer:
    def __init__(self, lang: str) -> None:
        self.lang = lang
        self.graph = build_graph()
        self.by_name = {a.name: a.id for a in self.graph.assets.values()}
        suffix = "" if lang == "en" else "-" + lang
        self.tab_dir = os.path.join(ROOT, "paper", "tables" + suffix)
        self.fig_dir = os.path.join(ROOT, "paper", "figures" + suffix)
        os.makedirs(self.tab_dir, exist_ok=True)
        os.makedirs(self.fig_dir, exist_ok=True)
        with open(os.path.join(RES, "summary.json"), encoding="utf-8") as fh:
            self.summary = json.load(fh)

    # -- helpers ---------------------------------------------------------
    def asset_name(self, english_name: str) -> str:
        aid = self.by_name.get(english_name)
        if aid is None:
            return english_name
        return t_asset(aid, self.lang, english_name)

    def path_str(self, english_path: str, trim: int = 0) -> str:
        hops = [self.asset_name(h.strip()) for h in english_path.split("->")]
        if trim:
            hops = [h[:trim].strip() for h in hops]
        return " \u2192 ".join(hops)

    @staticmethod
    def clip(text: str, limit: int) -> str:
        """Truncate on a word boundary, so labels never end mid-word."""
        if len(text) <= limit:
            return text
        cut = text[:limit].rsplit(" ", 1)[0]
        return (cut or text[:limit]).rstrip(" ,;-")

    def control_name(self, cid: str, limit: int = 0) -> str:
        name = t_control(cid, self.lang, CONTROLS[cid].name)
        return self.clip(name, limit) if limit else name

    def scenario_name(self, key: str, english: str) -> str:
        return SCENARIOS_PT[key] if self.lang == "pt" else english

    # -- tables ----------------------------------------------------------
    def tables(self) -> None:
        lang = self.lang
        rows = read("e1_top_paths_production.csv")[:10]
        write_latex_table(
            os.path.join(self.tab_dir, "e1_top_paths_production.tex"),
            TABLE_HEADERS["tab:top-paths"][lang],
            [(r["rank"], f"{float(r['likelihood']):.4f}", r["steps"],
              r["lowest_purdue_level"], self.path_str(r["path"]))
             for r in rows],
            caption=cap("tab:top-paths", lang), label="tab:top-paths",
            align="rrrrp{\\capmpathcol}", star=True)

        rows = read("e2_corpus_paths.csv")
        write_latex_table(
            os.path.join(self.tab_dir, "e2_corpus.tex"),
            TABLE_HEADERS["tab:corpus"][lang],
            [(r["id"], r["year"], r["victim"][:26],
              self.impact_short(r["impact"]),
              CONFIDENCE_PT[r["confidence"]] if lang == "pt" else r["confidence"],
              r["likelihood"], r["percentile_among_model_paths"])
             for r in rows],
            caption=cap("tab:corpus", lang), label="tab:corpus",
            align="llp{\\capmvictimcol}llrr", star=True)

        rows = [r for r in read("e3_node_criticality.csv") if r["zone"] != "Z-CONS"][:12]
        write_latex_table(
            os.path.join(self.tab_dir, "e3_chokepoints.tex"),
            TABLE_HEADERS["tab:chokepoints"][lang],
            [(self.clip(self.asset_name(r["name"]), 30), r["zone"], r["purdue"],
              r["likelihood_share"], r["paths"]) for r in rows],
            caption=cap("tab:chokepoints", lang), label="tab:chokepoints",
            align="p{\\capmnamecol}llrr")

        rows = [r for r in read("e4_scenarios.csv") if r["profile"] == "ransomware"]
        write_latex_table(
            os.path.join(self.tab_dir, "e4_scenarios.tex"),
            TABLE_HEADERS["tab:scenarios"][lang],
            [(self.scenario_name(r["scenario"], r["name"]), r["p_impact"],
              r["p_production_stop"], r["mean_downtime_h"], r["ale_musd"],
              r["control_cost_index"]) for r in rows],
            caption=cap("tab:scenarios", lang), label="tab:scenarios",
            align="p{\\capmvictimcol}rrrrr", star=True)

        rows = sorted(read("e5_marginal_controls.csv"),
                      key=lambda r: -float(r["ale_reduction_musd"]))[:10]
        write_latex_table(
            os.path.join(self.tab_dir, "e5_marginal.tex"),
            TABLE_HEADERS["tab:marginal"][lang],
            [(r["control"], self.control_name(r["control"]), r["ale_reduction_musd"],
              r["reduction_per_cost"], "; ".join(r["iec62443_3_3"].split("; ")[:2]))
             for r in rows],
            caption=cap("tab:marginal", lang), label="tab:marginal",
            align="lp{\\capmnamecol}rrp{\\capmstdcol}", star=True)

        rows = [r for r in read("e5_greedy_portfolio.csv") if r["profile"] == "ransomware"]
        write_latex_table(
            os.path.join(self.tab_dir, "e5_greedy.tex"),
            TABLE_HEADERS["tab:greedy"][lang],
            [(r["step"], r["control"], self.control_name(r["control"]),
              r["ale_after_musd"], r["gain_per_cost"]) for r in rows],
            caption=cap("tab:greedy", lang), label="tab:greedy", align="rlp{\\capmnamecol}rr", star=True)

        nec = self.summary["E5"]["necessity"][:10]
        write_latex_table(
            os.path.join(self.tab_dir, "e5_necessity.tex"),
            TABLE_HEADERS["tab:necessity"][lang],
            [(n["control"], self.control_name(n["control"]),
              f"{n['delta_ale_if_removed']:.2f}") for n in nec],
            caption=cap("tab:necessity", lang), label="tab:necessity",
            align="lp{\\capmnamecol}r")

        rows = read("e7_baselines.csv")
        def pnum(value: str) -> str:
            if not value:
                return "n/a"
            f = float(value)
            return "$<10^{-4}$" if f < 1e-4 else f"{f:.3f}"
        write_latex_table(
            os.path.join(self.tab_dir, "e7_baselines.tex"),
            TABLE_HEADERS["tab:baselines"][lang],
            [(r["ranking"], self.baseline_name(r["name"]), r["median_percentile"],
              r["mean_percentile"], f"{r['incidents_in_top_10pct']}/20",
              f"{r['incidents_in_top_25pct']}/20",
              r["kendall_tau_vs_capm"] or "n/a", pnum(r["wilcoxon_p_vs_capm"]),
              r["rank_biserial_effect"] or "n/a") for r in rows],
            caption=cap("tab:baselines", lang), label="tab:baselines",
            align="llrrrrrrr", star=True)

        rows = read("controls_standards_mapping.csv")
        write_latex_table(
            os.path.join(self.tab_dir, "controls_mapping.tex"),
            TABLE_HEADERS["tab:controls"][lang],
            [(r["control"], self.control_name(r["control"]), r["iec62443_3_3"],
              r["nist_csf_2_0"]) for r in rows],
            caption=cap("tab:controls", lang), label="tab:controls",
            align="lp{\\capmnamecol}p{\\capmstdcol}p{\\capmstdcol}", star=True)

    def baseline_name(self, english: str) -> str:
        if self.lang == "pt":
            return BASELINE_NAMES_PT.get(english, english)
        return english

    def impact_short(self, impact: str) -> str:
        short = impact.replace("imp_", "")
        return IMPACT_SHORT_PT.get(short, short) if self.lang == "pt" else short.replace("_", "\\_")

    # -- figures ---------------------------------------------------------
    def xbar(self, path: str, labels: Sequence[str], values: Sequence[float],
             xlabel: str, caption: str, label: str, height: str = "7.2cm",
             color: str = "MidnightBlue", star: bool = False) -> None:
        env = "figure*" if star else "figure"
        rows = "\n".join(f"        ({v:.6f},{i})" for i, v in enumerate(values))
        ticks = ",".join(str(i) for i in range(len(labels)))
        names = ",".join("{" + l + "}" for l in labels)
        body = f"""{HEAD}\\begin{{{env}}}[t]
\\centering
\\resizebox{{\\linewidth}}{{!}}{{%
\\begin{{tikzpicture}}
\\begin{{axis}}[
    xbar, width=\\linewidth, height={height},
    xlabel={{{xlabel}}},
    xmin=0, enlarge y limits=0.06,
    ytick={{{ticks}}}, yticklabels={{{names}}},
    y dir=reverse, ticklabel style={{font=\\scriptsize}},
    label style={{font=\\footnotesize}},
    nodes near coords, nodes near coords style={{font=\\tiny}},
    every node near coord/.append style={{/pgf/number format/fixed,
        /pgf/number format/precision=3}},
    xmajorgrids, grid style={{gray!25}}, axis lines*=left,
    bar width=6pt, tick align=outside,
]
\\addplot[fill={color}!70, draw={color}!80] coordinates {{
{rows}
}};
\\end{{axis}}
\\end{{tikzpicture}}}}
\\caption{{{caption}}}
\\label{{{label}}}
\\end{{{env}}}
"""
        with open(os.path.join(self.fig_dir, path), "w", encoding="utf-8") as fh:
            fh.write(body)

    def xbar_pairs(self, path: str, labels: Sequence[str],
                   series: Sequence[Tuple[str, Sequence[float]]], xlabel: str,
                   caption: str, label: str, height: str = "6.4cm") -> None:
        """Two grouped horizontal bar series sharing one category axis."""
        ticks = ",".join(str(i) for i in range(len(labels)))
        names = ",".join("{" + l + "}" for l in labels)
        colours = ["MidnightBlue", "Maroon"]
        plots = []
        for i, (name, values) in enumerate(series):
            coords = " ".join(f"({v:.6f},{j})" for j, v in enumerate(values))
            plots.append(f"\\addplot[fill={colours[i % 2]}!70, draw={colours[i % 2]}!85] "
                         f"coordinates {{{coords}}};")
        legend = ", ".join(name for name, _ in series)
        body = f"""{HEAD}\\begin{{figure}}[t]
\\centering
\\resizebox{{\\linewidth}}{{!}}{{%
\\begin{{tikzpicture}}
\\begin{{axis}}[
    xbar, width=\\linewidth, height={height},
    xlabel={{{xlabel}}}, xmin=0,
    ytick={{{ticks}}}, yticklabels={{{names}}}, y dir=reverse,
    enlarge y limits=0.12, bar width=5pt,
    ticklabel style={{font=\\scriptsize}}, label style={{font=\\footnotesize}},
    nodes near coords, nodes near coords style={{font=\\tiny}},
    every node near coord/.append style={{/pgf/number format/fixed,
        /pgf/number format/precision=2}},
    legend style={{at={{(0.98,0.03)}}, anchor=south east, font=\\scriptsize, draw=none}},
    xmajorgrids, grid style={{gray!25}}, axis lines*=left, tick align=outside,
]
{chr(10).join(plots)}
\\legend{{{legend}}}
\\end{{axis}}
\\end{{tikzpicture}}}}
\\caption{{{caption}}}
\\label{{{label}}}
\\end{{figure}}
"""
        with open(os.path.join(self.fig_dir, path), "w", encoding="utf-8") as fh:
            fh.write(body)

    def figures(self) -> None:
        lang = self.lang
        summary = self.summary

        rows = read("e1_top_paths_production.csv")[:10]
        labels = []
        for r in rows:
            hops = [self.clip(self.asset_name(h.strip()), 20)
                    for h in r["path"].split("->")][1:]
            # \textrightarrow, not $\to$: pgfplots re-expands tick labels when
            # "nodes near coords" is active and math macros break there
