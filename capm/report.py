"""Dependency-free reporting helpers: CSV, LaTeX tables and SVG figures.

Figures are emitted as hand-written SVG so that the whole experimental pipeline
runs on a bare CPython installation; the paper includes them directly.
"""

from __future__ import annotations

import csv
import os
from typing import Dict, Iterable, List, Optional, Sequence, Tuple

PALETTE = ["#1f4e79", "#c0504d", "#4f81bd", "#9bbb59", "#8064a2", "#f79646", "#4bacc6"]
INK = "#222222"
GRID = "#d9d9d9"


def ensure_dir(path: str) -> str:
    os.makedirs(path, exist_ok=True)
    return path


def write_csv(path: str, header: Sequence[str], rows: Iterable[Sequence[object]]) -> str:
    ensure_dir(os.path.dirname(path))
    with open(path, "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(header)
        for r in rows:
            w.writerow(list(r))
    return path


def _tex_escape(value: object) -> str:
    """Escape a data cell. The arrow U+2192 is the one character allowed to
    carry meaning: it is rendered as math, so path cells read as paths."""
    text = str(value)
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"),
                 ("#", r"\#"), ("_", r"\_"), ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"),
                 ("^", r"\textasciicircum{}")):
        text = text.replace(a, b)
    return text.replace("\u2192", "$\\to$")


def write_latex_table(
    path: str,
    header: Sequence[str],
    rows: Iterable[Sequence[object]],
    caption: str,
    label: str,
    align: Optional[str] = None,
    note: str = "",
    star: bool = False,
) -> str:
    ensure_dir(os.path.dirname(path))
    rows = list(rows)
    align = align or ("l" + "r" * (len(header) - 1))
    env = "table*" if star else "table"
    lines = [
        "% generated by the CAPM pipeline -- do not edit by hand",
        "\\begin{" + env + "}[t]",
        "\\centering",
        "\\caption{" + caption + "}",
        "\\label{" + label + "}",
        "\\capmtablefont",
        "\\begin{tabular}{" + align + "}",
        "\\toprule",
        # headers are author-provided LaTeX (they may contain math); only the
        # data cells are escaped
        " & ".join(str(h) for h in header) + " \\\\",
        "\\midrule",
    ]
    for r in rows:
        lines.append(" & ".join(_tex_escape(c) for c in r) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    if note:
        lines.append("\\\\[2pt]\\footnotesize " + note)
    lines.append("\\end{" + env + "}")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    return path


